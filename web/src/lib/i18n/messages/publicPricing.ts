type Catalog = Record<string, string>;

export type PublicPricingMessageKey =
  | `public.pricing.${string}`
  | `public.landing.pricing.${string}`
  | `public.landing.faq.${string}`
  | `public.footer.${string}`;

type PlanCopy = {
  name: string;
  description: string;
  cta: string;
  badge?: string;
  bullets: readonly string[];
  previewBullets: readonly string[];
};

function indexedEntries(prefix: string, values: readonly string[]): Catalog {
  return Object.fromEntries(values.map((value, index) => [`${prefix}.${index}`, value]));
}

function planEntries(id: PlanKey, copy: PlanCopy): Catalog {
  return {
    [`public.pricing.plan.${id}.name`]: copy.name,
    [`public.pricing.plan.${id}.description`]: copy.description,
    [`public.pricing.plan.${id}.cta`]: copy.cta,
    ...(copy.badge ? { [`public.pricing.plan.${id}.badge`]: copy.badge } : {}),
    ...indexedEntries(`public.pricing.plan.${id}.bullet`, copy.bullets),
    ...indexedEntries(`public.pricing.plan.${id}.previewBullet`, copy.previewBullets),
  };
}

function planCatalog(copy: Record<PlanKey, PlanCopy>): Catalog {
  return Object.assign({}, ...PRICING_TIERS.map(plan => planEntries(plan.id, copy[plan.id])));
}

function englishSourceCatalog(): Catalog {
  return Object.assign(
    {},
    ...PRICING_TIERS.map(plan => planEntries(plan.id, plan)),
    ...COMPARISON_SECTIONS.map((section, sectionIndex) => ({
      [`public.pricing.compare.section.${sectionIndex}`]: section.title,
      ...Object.assign({}, ...section.rows.map((row, rowIndex) => ({
        [`public.pricing.compare.row.${sectionIndex}.${rowIndex}`]: row.label,
        ...(row.note ? { [`public.pricing.compare.note.${sectionIndex}.${rowIndex}`]: row.note } : {}),
      }))),
    })),
    indexedEntries("public.pricing.enterprise.bullet", ENTERPRISE_PLAN.bullets),
    ...PRICING_FAQ.map((item, index) => ({
      [`public.pricing.faq.item.${index}.question`]: item.question,
      [`public.pricing.faq.item.${index}.answer`]: item.answer,
    })),
    ...FAQ_ITEMS.map((item, index) => ({
      [`public.landing.faq.item.${index}.question`]: item.question,
      [`public.landing.faq.item.${index}.answer`]: item.answer,
      ...(item.note ? { [`public.landing.faq.item.${index}.note`]: item.note } : {}),
    })),
  );
}

